using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Goobstation.Shared.Fishing;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Goobstation.Client.Fishing.Equipment;

/// <summary>
/// Shows the line, hook and bait currently attached to a fishing rod and lets the player take them out.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class FishingRodEquipmentWindow : FancyWindow
{
    [Dependency] private IEntityManager _ent = default!;
    [Dependency] private IPrototypeManager _proto = default!;

    private readonly SpriteSystem _sprite;

    public event Action<string>? OnEject;

    public FishingRodEquipmentWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sprite = _ent.System<SpriteSystem>();
    }

    public void UpdateState(FishingRodEquipmentBoundUserInterfaceState state)
    {
        SlotList.Children.Clear();

        foreach (var slot in state.Slots)
        {
            var prototype = slot.Prototype;
            SlotList.AddChild(new SlotRow(
                slot.Slot,
                Loc.GetString(slot.Name),
                prototype == null ? null : GetName(prototype),
                prototype == null ? string.Empty : GetDescription(prototype),
                prototype == null ? null : GetIcon(prototype),
                OnEjectPressed).Root);
        }
    }

    private void OnEjectPressed(string slot)
    {
        OnEject?.Invoke(slot);
    }

    private Texture? GetIcon(string prototype)
    {
        if (!_proto.TryIndex<EntityPrototype>(prototype, out var entProto))
            return null;

        return _sprite.GetPrototypeIcon(entProto).Default;
    }

    private string GetName(string prototype)
    {
        if (Loc.TryGetString($"ent-{prototype}", out var localized))
            return localized;

        return _proto.TryIndex<EntityPrototype>(prototype, out var entProto) ? entProto.Name : prototype;
    }

    private string GetDescription(string prototype)
    {
        if (Loc.TryGetString($"ent-{prototype}.desc", out var localized))
            return localized;

        return _proto.TryIndex<EntityPrototype>(prototype, out var entProto) ? entProto.Description : string.Empty;
    }

    private sealed class SlotRow
    {
        public readonly BoxContainer Root;

        public SlotRow(
            string slotId,
            string slotName,
            string? itemName,
            string itemDescription,
            Texture? icon,
            Action<string> onEject)
        {
            Root = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
                Margin = new Thickness(4f, 3f),
            };

            var header = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
            };

            var texture = new TextureRect
            {
                MinSize = new Vector2(40f, 40f),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                Texture = icon,
                VerticalAlignment = Control.VAlignment.Center,
            };
            header.AddChild(texture);

            // ClipText keeps long item names from pushing the eject button out of the row.
            var texts = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
                Margin = new Thickness(6f, 0f),
            };
            texts.AddChild(new Label { Text = slotName, ClipText = true });

            var eject = new Button
            {
                Text = Loc.GetString("fishing-rod-slot-eject"),
                MinSize = new Vector2(80f, 0f),
                VerticalAlignment = Control.VAlignment.Center,
            };
            eject.OnPressed += _ => onEject(slotId);

            if (itemName == null)
            {
                texts.AddChild(new Label
                {
                    Text = Loc.GetString("fishing-rod-slot-empty"),
                    FontColorOverride = Color.Gray,
                    ClipText = true,
                });
                eject.Disabled = true;
            }
            else
            {
                texts.AddChild(new Label { Text = itemName, ClipText = true });
            }

            header.AddChild(texts);
            header.AddChild(eject);
            Root.AddChild(header);

            // The description gets a full width line of its own, so it never competes with the button.
            if (itemName != null && !string.IsNullOrEmpty(itemDescription))
            {
                Root.AddChild(new RichTextLabel
                {
                    Text = itemDescription,
                    Margin = new Thickness(46f, 2f, 4f, 0f),
                });
            }
        }
    }
}
