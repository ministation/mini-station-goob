using Content.Client.UserInterface.Controls;
using Content.Goobstation.Shared.Fishing;
using Content.Goobstation.Shared.Fishing.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Goobstation.Client.Fishing.Equipment;

/// <summary>
/// Lists the traits of a fish so the player can pick the one to extract.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class FishingGeneGunWindow : FancyWindow
{
    public event Action<ProtoId<FishTraitPrototype>>? OnTraitSelected;

    public FishingGeneGunWindow()
    {
        RobustXamlLoader.Load(this);
    }

    public void UpdateState(FishingGeneGunBoundUserInterfaceState state)
    {
        TraitList.Children.Clear();

        foreach (var trait in state.Traits)
        {
            var traitId = trait.Trait;
            var button = new Button
            {
                Text = Loc.GetString(trait.Name),
                HorizontalExpand = true,
                Margin = new Thickness(0f, 2f),
            };
            button.OnPressed += _ => OnTraitSelected?.Invoke(traitId);
            TraitList.AddChild(button);
        }
    }
}
