using System.Linq;
using Content.Goobstation.Shared.Fishing.Prototypes;
using Content.Goobstation.Shared.Fishing.Sources;
using Content.Shared.EntityTable.EntitySelectors;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Goobstation.Client.Fishing.Sources;

[GenerateTypedNameReferences]
public sealed partial class FishCatalogWindow : DefaultWindow
{
    private sealed record CatalogFish(
        FishPrototype Proto,
        string Name,
        string Description,
        List<LocId> Sources);

    [Dependency] private IPrototypeManager _proto = default!;

    private readonly List<CatalogFish> _fish = new();
    private readonly List<CatalogFish> _filtered = new();
    private readonly Dictionary<string, List<LocId>> _sourceMap = new();

    public FishCatalogWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        BuildData();

        SearchBar.OnTextChanged += _ => RefreshList();
        FishList.OnItemSelected += args =>
        {
            if (args.ItemIndex < 0 || args.ItemIndex >= _filtered.Count)
                return;

            ShowDetails(_filtered[args.ItemIndex]);
        };

        RefreshList();
    }

    private void BuildData()
    {
        BuildSourceMap();

        foreach (var fish in _proto.EnumeratePrototypes<FishPrototype>())
        {
            if (!fish.ShowInCatalog)
                continue;

            var (name, description) = GetEntityNameAndDescription(fish.ID);
            _fish.Add(new CatalogFish(fish, name, description, GetSources(fish.ID)));
        }

        _fish.Sort((a, b) => string.Compare(a.Name, b.Name, StringComparison.CurrentCulture));
    }

    private void BuildSourceMap()
    {
        foreach (var source in _proto.EnumeratePrototypes<FishingSourcePrototype>())
        {
            if (source.CatalogDescription is not { } description)
                continue;

            var ids = new List<EntProtoId>();
            CollectIds(source.Table, ids);

            foreach (var id in ids)
            {
                if (!_sourceMap.TryGetValue(id.Id, out var list))
                    _sourceMap[id.Id] = list = new List<LocId>();

                if (!list.Contains(description))
                    list.Add(description);
            }
        }
    }

    private void CollectIds(EntityTableSelector selector, List<EntProtoId> ids)
    {
        switch (selector)
        {
            case EntSelector ent:
                ids.Add(ent.Id);
                break;
            case GroupSelector group:
                foreach (var child in group.Children)
                    CollectIds(child, ids);
                break;
            case AllSelector all:
                foreach (var child in all.Children)
                    CollectIds(child, ids);
                break;
            case NestedSelector nested:
                if (_proto.TryIndex(nested.TableId, out var table))
                    CollectIds(table.Table, ids);
                break;
        }
    }

    private List<LocId> GetSources(string fishId)
    {
        return _sourceMap.TryGetValue(fishId, out var sources) ? sources : new List<LocId>();
    }

    private void RefreshList()
    {
        var query = SearchBar.Text.Trim();

        _filtered.Clear();
        FishList.Clear();

        foreach (var fish in _fish)
        {
            if (query.Length > 0 && !fish.Name.Contains(query, StringComparison.CurrentCultureIgnoreCase))
                continue;

            _filtered.Add(fish);
            FishList.AddItem(fish.Name);
        }

        Details.Text = Loc.GetString("fishing-catalog-select");
    }

    private void ShowDetails(CatalogFish fish)
    {
        var msg = new FormattedMessage();

        msg.AddMarkupOrThrow($"[bold]{FormattedMessage.EscapeText(fish.Name)}[/bold]");
        msg.PushNewline();

        if (!string.IsNullOrEmpty(fish.Description))
        {
            msg.AddText(fish.Description);
            msg.PushNewline();
        }

        msg.PushNewline();
        var proto = fish.Proto;
        AddLine(msg, Loc.GetString("fishing-catalog-size", ("size", MathF.Round(proto.AverageSize))));
        AddLine(msg, Loc.GetString("fishing-catalog-weight", ("weight", MathF.Round(proto.AverageWeight))));
        AddLine(msg, Loc.GetString("fishing-catalog-fluid", ("fluid", FishUiHelpers.GetFluidName(proto.Fluid))));
        AddLine(msg, Loc.GetString("fishing-catalog-temperature",
            ("min", FishUiHelpers.KelvinToCelsius(proto.TemperatureMin)),
            ("max", FishUiHelpers.KelvinToCelsius(proto.TemperatureMax))));
        AddLine(msg, Loc.GetString("fishing-catalog-difficulty", ("difficulty", GetDifficultyName(proto))));

        if (proto.Beauty != 0)
            AddLine(msg, Loc.GetString("fishing-catalog-beauty", ("beauty", proto.Beauty)));

        if (proto.Traits.Count > 0)
        {
            msg.PushNewline();
            AddLine(msg, Loc.GetString("fishing-catalog-traits-title"));

            foreach (var traitId in proto.Traits)
            {
                if (!_proto.TryIndex(traitId, out FishTraitPrototype? trait))
                    continue;

                msg.AddMarkupOrThrow("  - ");
                msg.AddText(Loc.GetString(trait.CatalogDescription));
                msg.PushNewline();
            }
        }

        msg.PushNewline();

        if (fish.Sources.Count == 0)
        {
            AddLine(msg, Loc.GetString("fishing-catalog-sources-unknown"));
        }
        else
        {
            var sourceNames = fish.Sources.Select(source => Loc.GetString(source)).ToList();
            sourceNames.Sort(StringComparer.CurrentCulture);
            AddLine(msg, Loc.GetString("fishing-catalog-sources", ("sources", string.Join(", ", sourceNames))));
        }

        Details.SetMessage(msg);
    }

    private string GetDifficultyName(FishPrototype proto)
    {
        var difficulty = proto.DifficultyModifier;

        foreach (var traitId in proto.Traits)
        {
            if (_proto.TryIndex(traitId, out FishTraitPrototype? trait))
                difficulty += trait.AddedDifficulty;
        }

        return difficulty switch
        {
            < 10f => Loc.GetString("fishing-catalog-difficulty-easy"),
            < 20f => Loc.GetString("fishing-catalog-difficulty-medium"),
            _ => Loc.GetString("fishing-catalog-difficulty-hard"),
        };
    }

    private static void AddLine(FormattedMessage msg, string line)
    {
        msg.AddText(line);
        msg.PushNewline();
    }

    private (string Name, string Description) GetEntityNameAndDescription(string fishId)
    {
        var name = fishId;
        var description = string.Empty;

        if (_proto.TryIndex<EntityPrototype>(fishId, out var proto))
        {
            name = proto.Name;
            description = proto.Description;
        }

        if (Loc.TryGetString($"ent-{fishId}", out var localizedName))
            name = localizedName;

        if (Loc.TryGetString($"ent-{fishId}.desc", out var localizedDescription))
            description = localizedDescription;

        return (name, description);
    }
}
