namespace Content.Goobstation.Client.Achievements.UI;

/// <summary>
/// Achievements browser embedded into the shared rewards menu. Builds itself from the client
/// <see cref="AchievementsSystem"/> cache and refreshes whenever the system pushes new state.
/// </summary>
public sealed partial class AchievementsPanel : BoxContainer
{
    private static readonly Color HeaderBackground = Color.FromHex("#15151c");
    private static readonly Color HeaderBorder = Color.FromHex("#2c2c36");
    private static readonly Color DividerColor = Color.FromHex("#26262f");
    private static readonly Color TrackColor = Color.FromHex("#26262f");
    private static readonly Color GoldColor = Color.FromHex("#c9a13b");
    private static readonly Color GoldText = Color.FromHex("#eccd74");
    private static readonly Color GoldBackground = Color.FromHex("#2b2411");
    private static readonly Color MutedText = Color.FromHex("#8f96a4");
    private static readonly Color AccentColor = Color.FromHex("#9a8fb5");

    [Dependency] private IPrototypeManager _proto = default!;
    [Dependency] private IEntityManager _entMan = default!;

    private readonly AchievementsSystem _system;
    private readonly SpriteSystem _sprite;
    private readonly Label _summaryLabel;
    private readonly ProgressBar _summaryBar;
    private readonly Label _percentLabel;
    private readonly Label _coinsLabel;
    private readonly BoxContainer _list;

    public AchievementsPanel()
    {
        IoCManager.InjectDependencies(this);

        _sprite = _entMan.System<SpriteSystem>();
        _system = _entMan.System<AchievementsSystem>();

        Orientation = LayoutOrientation.Vertical;
        SeparationOverride = 6;
        HorizontalExpand = true;
        VerticalExpand = true;
        Margin = new Thickness(4);

        var (header, summaryLabel, summaryBar, percentLabel, coinsLabel) = BuildSummary();
        _summaryLabel = summaryLabel;
        _summaryBar = summaryBar;
        _percentLabel = percentLabel;
        _coinsLabel = coinsLabel;
        AddChild(header);

        _list = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            HorizontalExpand = true,
        };

        var scroll = new ScrollContainer
        {
            HScrollEnabled = false,
            HorizontalExpand = true,
            VerticalExpand = true,
        };
        scroll.AddChild(_list);
        AddChild(scroll);
    }

    private (Control Header, Label Summary, ProgressBar Bar, Label Percent, Label Coins) BuildSummary()
    {
        var header = new PanelContainer
        {
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 2),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = HeaderBackground,
                BorderColor = HeaderBorder,
                BorderThickness = new Thickness(1),
            },
        };

        var row = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            SeparationOverride = 10,
            Margin = new Thickness(12, 8, 12, 8),
        };
        header.AddChild(row);

        var summaryLabel = new Label
        {
            Text = Loc.GetString("achievements-window-loading"),
            StyleClasses = { "LabelKeyText" },
            VerticalAlignment = VAlignment.Center,
        };
        row.AddChild(summaryLabel);

        var summaryBar = new ProgressBar
        {
            HorizontalExpand = true,
            MinValue = 0,
            MaxValue = 1,
            SetHeight = 8,
            VerticalAlignment = VAlignment.Center,
            BackgroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = TrackColor },
            ForegroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = GoldColor },
        };
        row.AddChild(summaryBar);

        var percentLabel = new Label
        {
            StyleClasses = { "LabelSubText" },
            Modulate = MutedText,
            VerticalAlignment = VAlignment.Center,
            MinSize = new Vector2(38, 0),
            HorizontalAlignment = HAlignment.Right,
        };
        row.AddChild(percentLabel);

        // Coins already banked from achievements, mirroring the reward badge on the cards.
        var coinPill = new PanelContainer
        {
            VerticalAlignment = VAlignment.Center,
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = GoldBackground,
                BorderColor = GoldColor.WithAlpha(0.9f),
                BorderThickness = new Thickness(1),
            },
        };
        row.AddChild(coinPill);

        var coinRow = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            SeparationOverride = 5,
            Margin = new Thickness(9, 3, 11, 3),
            VerticalAlignment = VAlignment.Center,
        };
        coinPill.AddChild(coinRow);

        var cache = IoCManager.Resolve<IResourceCache>();
        var coinTexture = cache.TryGetResource<TextureResource>(new ResPath(AntagTokenCatalog.CurrencyIconPath), out var coinRes)
            ? coinRes.Texture
            : cache.GetTexture("/Textures/_Mini/Interface/Coin.png");

        var coinsLabel = new Label
        {
            Text = "0",
            FontColorOverride = GoldText,
            VerticalAlignment = VAlignment.Center,
        };
        coinsLabel.ToolTip = Loc.GetString("achievements-window-summary-coins-tooltip", ("coins", 0));
        coinRow.AddChild(coinsLabel);

        coinRow.AddChild(new TextureRect
        {
            Texture = coinTexture,
            SetSize = new Vector2(16, 16),
            Stretch = TextureRect.StretchMode.KeepAspectCentered,
            VerticalAlignment = VAlignment.Center,
        });

        return (header, summaryLabel, summaryBar, percentLabel, coinsLabel);
    }

    // Subscribe only while the panel is actually in the UI tree: the rewards window is created
    // outside the BUI disposal path, so a Dispose-based unsubscribe would leak handlers on every
    // open. ExitedTree is raised when the window closes in any path.
    protected override void EnteredTree()
    {
        base.EnteredTree();

        _system.Updated -= OnUpdated;
        _system.Updated += OnUpdated;
        OnUpdated();
        _system.RequestState();
    }

    protected override void ExitedTree()
    {
        _system.Updated -= OnUpdated;
        base.ExitedTree();
    }

    private void OnUpdated()
    {
        if (_system.Achievements is { } achievements)
            UpdateAchievements(achievements);
    }

    public void UpdateAchievements(List<AchievementData> achievements)
    {
        _list.RemoveAllChildren();

        var unlocked = achievements.Count(a => a.UnlockedAt != null);
        var coins = achievements.Where(a => a.UnlockedAt != null).Sum(a => a.CoinReward);
        var percent = achievements.Count == 0 ? 0 : (int) MathF.Round(unlocked * 100f / achievements.Count);

        _summaryLabel.Text = Loc.GetString("achievements-window-summary",
            ("unlocked", unlocked),
            ("total", achievements.Count));
        _summaryBar.Value = achievements.Count == 0 ? 0f : unlocked / (float) achievements.Count;
        _percentLabel.Text = Loc.GetString("achievements-window-summary-percent", ("percent", percent));
        _coinsLabel.Text = coins.ToString();
        _coinsLabel.ToolTip = Loc.GetString("achievements-window-summary-coins-tooltip", ("coins", coins));

        if (achievements.Count == 0)
        {
            _list.AddChild(new Label
            {
                Text = Loc.GetString("achievements-window-empty"),
                Modulate = MutedText,
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(0, 24, 0, 0),
            });
            return;
        }

        var categories = _proto.EnumeratePrototypes<AchievementCategoryPrototype>()
            .OrderBy(c => c.Priority);

        foreach (var category in categories)
        {
            var entries = achievements
                .Where(a => a.Category == category.ID)
                .OrderByDescending(a => a.UnlockedAt != null)
                .ThenByDescending(a => a.UnlockedAt)
                .ToList();

            if (entries.Count == 0)
                continue;

            var categoryUnlocked = entries.Count(a => a.UnlockedAt != null);

            _list.AddChild(new PanelContainer
            {
                HorizontalExpand = true,
                MinSize = new Vector2(0, 1),
                Margin = new Thickness(2, 12, 2, 0),
                PanelOverride = new StyleBoxFlat { BackgroundColor = DividerColor },
            });

            var categoryRow = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
                SeparationOverride = 8,
                Margin = new Thickness(2, 6, 4, 4),
            };
            _list.AddChild(categoryRow);

            categoryRow.AddChild(new PanelContainer
            {
                MinSize = new Vector2(4, 15),
                VerticalAlignment = VAlignment.Center,
                PanelOverride = new StyleBoxFlat { BackgroundColor = AccentColor.WithAlpha(0.8f) },
            });

            categoryRow.AddChild(new Label
            {
                Text = Loc.GetString(category.Name),
                StyleClasses = { "LabelHeading" },
                HorizontalExpand = true,
            });

            categoryRow.AddChild(new Label
            {
                Text = Loc.GetString("achievements-window-category-count",
                    ("unlocked", categoryUnlocked),
                    ("total", entries.Count)),
                StyleClasses = { "LabelSubText" },
                Modulate = MutedText,
                VerticalAlignment = VAlignment.Center,
            });

            foreach (var entry in entries)
                _list.AddChild(new AchievementEntry(entry, _sprite));
        }
    }
}
