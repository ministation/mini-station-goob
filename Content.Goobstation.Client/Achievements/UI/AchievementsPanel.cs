using System.Linq;
using Content.Goobstation.Shared.Achievements;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Shared.GameObjects;
using Robust.Shared.IoC;
using Robust.Shared.Prototypes;

namespace Content.Goobstation.Client.Achievements.UI;

/// <summary>
/// Achievements browser embedded into the shared rewards menu. Builds itself from the client
/// <see cref="AchievementsSystem"/> cache and refreshes whenever the system pushes new state.
/// </summary>
public sealed partial class AchievementsPanel : BoxContainer
{
    [Dependency] private IPrototypeManager _proto = default!;
    [Dependency] private IEntityManager _entMan = default!;

    private readonly AchievementsSystem _system;
    private readonly SpriteSystem _sprite;
    private readonly Label _summaryLabel;
    private readonly ProgressBar _summaryBar;
    private readonly BoxContainer _list;

    public AchievementsPanel()
    {
        IoCManager.InjectDependencies(this);

        _sprite = _entMan.System<SpriteSystem>();
        _system = _entMan.System<AchievementsSystem>();

        Orientation = LayoutOrientation.Vertical;
        SeparationOverride = 6;
        HorizontalExpand = true;
        VerticalExpand = true;
        Margin = new Thickness(4);

        var summaryRow = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            Margin = new Thickness(0, 0, 0, 4),
        };

        _summaryLabel = new Label
        {
            StyleClasses = { "LabelHeading" },
            Text = Loc.GetString("achievements-window-loading"),
        };
        _summaryBar = new ProgressBar
        {
            HorizontalExpand = true,
            MinValue = 0,
            MaxValue = 1,
            SetHeight = 14,
            Margin = new Thickness(12, 0, 0, 0),
            VerticalAlignment = VAlignment.Center,
        };

        summaryRow.AddChild(_summaryLabel);
        summaryRow.AddChild(_summaryBar);
        AddChild(summaryRow);

        _list = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            HorizontalExpand = true,
        };

        var scroll = new ScrollContainer
        {
            HScrollEnabled = false,
            HorizontalExpand = true,
            VerticalExpand = true,
        };
        scroll.AddChild(_list);
        AddChild(scroll);

    }

    // Subscribe only while the panel is actually in the UI tree: the rewards window is created
    // outside the BUI disposal path, so a Dispose-based unsubscribe would leak handlers on every
    // open. ExitedTree is raised when the window closes in any path.
    protected override void EnteredTree()
    {
        base.EnteredTree();

        _system.Updated -= OnUpdated;
        _system.Updated += OnUpdated;
        OnUpdated();
        _system.RequestState();
    }

    protected override void ExitedTree()
    {
        _system.Updated -= OnUpdated;
        base.ExitedTree();
    }

    private void OnUpdated()
    {
        if (_system.Achievements is { } achievements)
            UpdateAchievements(achievements);
    }

    public void UpdateAchievements(List<AchievementData> achievements)
    {
        _list.RemoveAllChildren();

        var unlocked = achievements.Count(a => a.UnlockedAt != null);
        var coins = achievements.Where(a => a.UnlockedAt != null).Sum(a => a.CoinReward);
        _summaryLabel.Text = Loc.GetString("achievements-window-summary-coins",
            ("unlocked", unlocked),
            ("total", achievements.Count),
            ("coins", coins));
        _summaryBar.Value = achievements.Count == 0 ? 0f : unlocked / (float) achievements.Count;

        var categories = _proto.EnumeratePrototypes<AchievementCategoryPrototype>()
            .OrderBy(c => c.Priority);

        foreach (var category in categories)
        {
            var entries = achievements
                .Where(a => a.Category == category.ID)
                .OrderByDescending(a => a.UnlockedAt != null)
                .ThenByDescending(a => a.UnlockedAt)
                .ToList();

            if (entries.Count == 0)
                continue;

            _list.AddChild(new Label
            {
                Text = Loc.GetString("achievements-window-tab-category",
                    ("name", Loc.GetString(category.Name)),
                    ("unlocked", entries.Count(a => a.UnlockedAt != null)),
                    ("total", entries.Count)),
                StyleClasses = { "LabelHeading" },
                Margin = new Thickness(2, 8, 0, 2),
            });

            foreach (var entry in entries)
                _list.AddChild(new AchievementEntry(entry, _sprite));
        }
    }

}
