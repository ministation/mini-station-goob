using Content.Client.UserInterface;
using Content.Shared.Administration;
using Content.Shared._Mini.NeuroAHelp;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;
using Content.Client._Amour.Stickers.UI;
using System.Numerics;

namespace Content.Client.Administration.UI.Bwoink
{
    [GenerateTypedNameReferences]
    public sealed partial class BwoinkPanel : BoxContainer
    {
        private readonly Action<string> _messageSender;

        public int Unread { get; private set; } = 0;
        public DateTime LastMessage { get; private set; } = DateTime.MinValue;
        private List<string> PeopleTyping { get; set; } = new();
        private bool _introShown;
        public event Action<string>? InputTextChanged;

        public BwoinkPanel(Action<string> messageSender)
        {
            RobustXamlLoader.Load(this);

            var msg = new FormattedMessage();
            msg.PushColor(Color.LightGray);
            msg.AddText(Loc.GetString("bwoink-system-messages-being-relayed-to-discord"));
            msg.Pop();
            RelayedToDiscordLabel.SetMessage(msg);

            _messageSender = messageSender;

            // Mini edit: the actionSearchBox texture was almost invisible on the dark ahelp panel;
            // give the input a proper dark background with a readable border instead.
            var senderBox = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#14141C"),
                BorderColor = Color.FromHex("#45455C"),
                BorderThickness = new Thickness(1),
                ContentMarginTopOverride = 6,
                ContentMarginBottomOverride = 6,
                ContentMarginLeftOverride = 8,
                ContentMarginRightOverride = 8,
            };
            SenderLineEdit.StyleBoxOverride = senderBox;

            OnVisibilityChanged += c =>
            {
                if (c.Visible)
                    Unread = 0;
            };
            SenderLineEdit.OnTextEntered += Input_OnTextEntered;
            SenderLineEdit.OnTextChanged += Input_OnTextChanged;

            // Amour edit start
            StickerBtn.OnStickerSelected += sticker => StickerInputHelper.InsertSticker(SenderLineEdit, sticker);
            // Amour edit end

            UpdateTypingIndicator();
            UiChatFonts.ApplyToOutput(TextOutput);
        }

        public void RefreshOutputFont() => UiChatFonts.ApplyToOutput(TextOutput);

        public void AttachRatingPanel(AHelpRatingPanel panel)
        {
            RatingHost.DisposeAllChildren();
            RatingHost.AddChild(panel);
        }

        private void Input_OnTextEntered(LineEdit.LineEditEventArgs args)
        {
            if (string.IsNullOrWhiteSpace(args.Text))
                return;

            _messageSender.Invoke(args.Text);
            SenderLineEdit.Clear();
        }

        private void Input_OnTextChanged(LineEdit.LineEditEventArgs args)
        {
            InputTextChanged?.Invoke(args.Text);
        }

        public void ShowIntroductoryMessageIfNeeded()
        {
            if (_introShown)
                return;

            _introShown = true;

            var formatted = new FormattedMessage();
            formatted.PushColor(Color.LightGray);
            formatted.AddText(Loc.GetString("bwoink-system-introductory-message"));
            formatted.Pop();
            TextOutput.AddMessage(formatted);
        }

        public void ReceiveLine(SharedBwoinkSystem.BwoinkTextMessage message)
        {
            if (!Visible)
                Unread++;

            var formatted = new FormattedMessage(1);
            // Mini edit start: URLs in AHelp messages become clickable links.
            var markup = $"[color=gray]{message.SentAt.ToShortTimeString()}[/color] {AHelpLinkHelper.Linkify(message.Text)}";
            if (!formatted.TryAddMarkup(markup, out _))
                formatted.AddMarkupPermissive(markup);
            TextOutput.AddMessage(formatted, AHelpLinkHelper.AllowedTags);
            // Mini edit end
            LastMessage = message.SentAt;
        }

        private void UpdateTypingIndicator()
        {
            var msg = new FormattedMessage();
            msg.PushColor(Color.LightGray);

            var text = PeopleTyping.Count == 0
                ? string.Empty
                : Loc.GetString("bwoink-system-typing-indicator",
                    ("players", string.Join(", ", PeopleTyping)),
                    ("count", PeopleTyping.Count));

            msg.AddText(text);
            msg.Pop();

            TypingIndicator.SetMessage(msg);
        }

        public void UpdatePlayerTyping(string name, bool typing)
        {
            if (typing)
            {
                if (PeopleTyping.Contains(name))
                    return;

                PeopleTyping.Add(name);
                Timer.Spawn(TimeSpan.FromSeconds(10), () =>
                {
                    if (Disposed)
                        return;

                    PeopleTyping.Remove(name);
                    UpdateTypingIndicator();
                });
            }
            else
            {
                PeopleTyping.Remove(name);
            }

            UpdateTypingIndicator();
        }

        // Мини: кольцо-индикатор нейропомощника.

        /// <summary>Счетчик обновлений статуса, чтобы таймер скрытия не убил более свежий статус.</summary>
        private int _neuroStatusVersion;

        /// <summary>
        /// Показывает состояние нейропомощника в тикете: кольцо с цветом состояния и контекстом
        /// работы («читаю логи раунда»). Idle скрывает полосу; Done гаснет сам через 15 секунд.
        /// </summary>
        public void SetNeuroStatus(NeuroAHelpState state, string assistantName, string detail)
        {
            _neuroStatusVersion++;
            var version = _neuroStatusVersion;

            if (state == NeuroAHelpState.Idle)
            {
                NeuroStatusHost.Visible = false;
                return;
            }

            var (color, glyph) = state switch
            {
                NeuroAHelpState.Working => ("#8ab4f8", "◐"),
                NeuroAHelpState.Done => ("#41f097", "●"),
                NeuroAHelpState.Failed => ("#f0a041", "●"),
                NeuroAHelpState.Silent => ("#8a8ab0", "○"),
                NeuroAHelpState.Muted => ("#b05555", "○"),
                _ => ("#8a8ab0", "○"),
            };

            NeuroRing.SetState(state);
            NeuroStatusHost.Visible = true;
            NeuroStatusHost.ToolTip = detail;

            if (string.IsNullOrWhiteSpace(assistantName))
                assistantName = Loc.GetString("neuro-ahelp-assistant-name");

            var label = Loc.GetString("neuro-ahelp-status-label",
                ("name", assistantName), ("color", color), ("glyph", glyph), ("detail", detail));
            var msg = new FormattedMessage();
            if (!msg.TryAddMarkup(label, out _))
                msg.AddMarkupPermissive(label);
            NeuroStatusLabel.SetMessage(msg);

            if (state == NeuroAHelpState.Done)
            {
                // Зелёное «ответил» - транзитное состояние: гасим, если статус не сменился.
                Timer.Spawn(TimeSpan.FromSeconds(15), () =>
                {
                    if (Disposed || _neuroStatusVersion != version)
                        return;

                    NeuroStatusHost.Visible = false;
                });
            }
        }

        protected override void Dispose(bool disposing)
        {
            base.Dispose(disposing);

            InputTextChanged = null;
        }
    }
}
