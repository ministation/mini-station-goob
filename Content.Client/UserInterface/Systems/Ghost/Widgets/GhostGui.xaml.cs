using Content.Client._CorvaxGoob.GhostBar.Controls;
using Content.Client._Mini.UserInterface.Systems.Ghost.Controls;
using Content.Client.Stylesheets;
using Robust.Client.AutoGenerated;
using Robust.Client.Console;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.UserInterface.Systems.Ghost.Widgets;

[GenerateTypedNameReferences]
public sealed partial class GhostGui : UIWidget
{
    [Dependency] private readonly IClientConsoleHost _consoleHost = default!;

    public MiniGhostTargetWindow TargetWindow { get; }
    public GhostBarRulesWindow GhostBarWindow { get; } // CorvaxGoob-GhostBar

    public event Action? RequestWarpsPressed;
    public event Action? ReturnToBodyPressed;
    public event Action? GhostRolesPressed;
    public event Action? GhostBarPressed; // CorvaxGoob-GhostBar
    public event Action? ThunderdomePressed; // Goobstation - Thunderdome
    public event Action? ReturnToRoundPressed; // FREAKY EDIT / Mini
    private int _prevNumberRoles;

    public GhostGui()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        TargetWindow = new MiniGhostTargetWindow();

        GhostBarWindow = new GhostBarRulesWindow(); // CorvaxGoob-GhostBar

        MouseFilter = MouseFilterMode.Ignore;

        GhostWarpButton.OnPressed += _ => RequestWarpsPressed?.Invoke();
        ReturnToBodyButton.OnPressed += _ => ReturnToBodyPressed?.Invoke();
        GhostRolesButton.OnPressed += _ => GhostRolesPressed?.Invoke();
        GhostRolesButton.OnPressed += _ => GhostRolesButton.StyleClasses.Remove(StyleClass.Negative);
        GhostBarButton.OnPressed += _ => GhostBarPressed?.Invoke(); // CorvaxGoob-GhostBar
        ThunderdomeButton.OnPressed += _ => ThunderdomePressed?.Invoke(); // Goobstation - Thunderdome
        AntagTokensButton.OnPressed += _ => OpenAntagTokens(); // Mini-station
    }

    public void Hide()
    {
        TargetWindow.Close();
        GhostBarWindow.Close(); // CorvaxGoob-GhostBar
        Visible = false;
    }

    // Ghoob edit && CorvaxGoob edit : GhostBar
    public void Update(int? roles, bool? canReturnToBody, bool? canEnterGhostBar = true, bool? canTakeGhostRoles = true)
    {
        ReturnToBodyButton.Disabled = !canReturnToBody ?? true;
        GhostBarButton.Visible = false; // Mini: ghost bar disabled
        GhostBarButton.Disabled = true;
        // Goobstation start
        GhostRolesButton.Disabled = !canTakeGhostRoles ?? true;
        // Goobstation end

        if (roles != null)
        {
            GhostRolesButton.Text = Loc.GetString("ghost-gui-ghost-roles-button", ("count", roles));

            if (roles > _prevNumberRoles)
            {
                GhostRolesButton.StyleClasses.Add(StyleClass.Negative);
            }

            _prevNumberRoles = (int)roles;
        }

        TargetWindow.Populate();
    }

    // Mini-station: hide ghost-role / antag / bar / thunderdome during Typan war
    public void SetWarModeRestrictions(bool active)
    {
        GhostRolesButton.Visible = !active;
        AntagTokensButton.Visible = !active;
        GhostBarButton.Visible = !active;
        ThunderdomeButton.Visible = !active;
    }

    // Goobstation - Thunderdome
    public void UpdateThunderdome(int playerCount)
    {
        ThunderdomeButton.Text = Loc.GetString("thunderdome-ghost-button", ("count", playerCount));
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (disposing)
        {
            TargetWindow.Dispose();
            GhostBarWindow.Dispose(); // CorvaxGoob-GhostBar
        }
    }

    private void OpenAntagTokens()
    {
        _consoleHost.ExecuteCommand("antagtokenmenu");
    }
}
