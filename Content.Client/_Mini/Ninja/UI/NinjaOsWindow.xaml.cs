namespace Content.Client._Mini.Ninja.UI;

/// <summary>
/// Window of the suit Spider OS. Shows one module per tier for the three ninja paths,
/// lets the player install them and powers the suit on or off.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NinjaOsWindow : FancyWindow
{
    private const float CellWidth = 168f;
    private const float CellHeight = 66f;
    private const float TierCellWidth = 64f;

    private static readonly NinjaPath[] PathOrder = { NinjaPath.Ghost, NinjaPath.Snake, NinjaPath.Steel };

    private static readonly Color PanelColor = Color.FromHex("#101318");
    private static readonly Color CellColor = Color.FromHex("#171B22");
    private static readonly Color BorderColor = Color.FromHex("#2A313C");
    private static readonly Color TextColor = Color.FromHex("#D7DEE8");
    private static readonly Color DimTextColor = Color.FromHex("#8A94A3");
    private static readonly Color OkColor = Color.FromHex("#2ECC71");
    private static readonly Color ErrorColor = Color.FromHex("#E5484D");
    private static readonly Color LockedColor = Color.FromHex("#E0B341");

    private static readonly Dictionary<NinjaPath, Color> PathColors = new()
    {
        [NinjaPath.Ghost] = Color.FromHex("#4C6FFF"),
        [NinjaPath.Snake] = Color.FromHex("#2ECC71"),
        [NinjaPath.Steel] = Color.FromHex("#E5484D"),
    };

    private readonly SpriteSystem _sprite;

    private List<NinjaModulePrototype> _modules = new();
    private int _maxTier = 5;
    private string? _failReason;
    private bool _powerLocked;

    /// <summary>
    /// Raised when the player picks the module of the given tier and path.
    /// </summary>
    public event Action<int, NinjaPath>? OnModuleSelected;

    /// <summary>
    /// Raised when the player presses the suit power button.
    /// </summary>
    public event Action? OnSuitPowerPressed;

    /// <summary>
    /// Raised when the player selects a colour, style or head option.
    /// </summary>
    public event Action<NinjaColorway, NinjaStyle, bool>? OnAppearanceSelected;

    private NinjaColorway _colorway = NinjaColorway.Green;
    private NinjaStyle _style = NinjaStyle.Old;
    private bool _helmet = true;
    private bool _appearanceLocked;

    public NinjaOsWindow()
    {
        RobustXamlLoader.Load(this);

        _sprite = IoCManager.Resolve<IEntitySystemManager>().GetEntitySystem<SpriteSystem>();

        PowerButton.OnPressed += _ => OnSuitPowerPressed?.Invoke();
        NinjaCloseButton.OnPressed += _ => Close();

        ColorGreenButton.OnPressed += _ => SelectAppearance(NinjaColorway.Green, _style, _helmet);
        ColorRedButton.OnPressed += _ => SelectAppearance(NinjaColorway.Red, _style, _helmet);
        ColorBlueButton.OnPressed += _ => SelectAppearance(NinjaColorway.Blue, _style, _helmet);
        StyleOldButton.OnPressed += _ => SelectAppearance(_colorway, NinjaStyle.Old, _helmet);
        StyleNewButton.OnPressed += _ => SelectAppearance(_colorway, NinjaStyle.New, true);
        HeadHelmetButton.OnPressed += _ => SelectAppearance(_colorway, _style, true);
        HeadScarfButton.OnPressed += _ => SelectAppearance(_colorway, NinjaStyle.Old, false);

        UpdatePower(false);
        StatusLabel.Text = Loc.GetString("ninja-os-loading");
    }

    public void UpdateState(NinjaOsBoundUserInterfaceState state, List<NinjaModulePrototype> modules, int maxTier)
    {
        _modules = modules;
        _maxTier = Math.Max(1, maxTier);

        _colorway = state.PendingColorway;
        _style = state.PendingStyle;
        _helmet = state.PendingHelmet;
        _appearanceLocked = state.SuitActivated;

        BuildModules(state);
        UpdateAppearanceControls();
        UpdatePower(state.SuitActivated);
        UpdateSummary(state);
        ApplyFailReason();
    }

    private void SelectAppearance(NinjaColorway colorway, NinjaStyle style, bool helmet)
    {
        if (_appearanceLocked)
            return;

        // The new style always uses the helmet.
        if (style == NinjaStyle.New)
            helmet = true;

        _colorway = colorway;
        _style = style;
        _helmet = helmet;
        UpdateAppearanceControls();
        OnAppearanceSelected?.Invoke(colorway, style, helmet);
    }

    private void UpdateAppearanceControls()
    {
        var locked = _appearanceLocked;

        ColorGreenButton.Disabled = locked;
        ColorRedButton.Disabled = locked;
        ColorBlueButton.Disabled = locked;
        StyleOldButton.Disabled = locked;
        StyleNewButton.Disabled = locked;
        HeadHelmetButton.Disabled = locked || _style == NinjaStyle.New;
        HeadScarfButton.Disabled = locked || _style == NinjaStyle.New;

        Highlight(ColorGreenButton, _colorway == NinjaColorway.Green);
        Highlight(ColorRedButton, _colorway == NinjaColorway.Red);
        Highlight(ColorBlueButton, _colorway == NinjaColorway.Blue);
        Highlight(StyleOldButton, _style == NinjaStyle.Old);
        Highlight(StyleNewButton, _style == NinjaStyle.New);
        Highlight(HeadHelmetButton, _helmet);
        Highlight(HeadScarfButton, !_helmet);
    }

    private static void Highlight(Button button, bool selected)
    {
        button.ModulateSelfOverride = selected ? Color.White : DimTextColor;
    }

    public void SetPowerButtonEnabled(bool enabled)
    {
        _powerLocked = !enabled;
        PowerButton.Disabled = !enabled;
    }

    public void UpdatePower(bool activated)
    {
        PowerButton.Text = Loc.GetString(activated ? "ninja-os-deactivate" : "ninja-os-activate");
        PowerButton.Disabled = _powerLocked;

        StatusLabel.Text = $"{Loc.GetString("ninja-os-status")} " +
                           Loc.GetString(activated ? "ninja-os-status-active" : "ninja-os-status-idle");
        StatusLabel.FontColorOverride = activated ? OkColor : TextColor;
    }

    public void SetFailReason(string? failReason)
    {
        _failReason = failReason;
        ApplyFailReason();
    }

    public void ShowBootLog(bool activated)
    {
        BootPanel.Visible = true;
        BootTitleLabel.Text = Loc.GetString(activated ? "ninja-os-boot-title" : "ninja-os-shutdown-title");
        BootLog.Clear();
        SetBootProgress(0f);
    }

    public void AppendBootLog(string text, bool error)
    {
        var color = error ? ErrorColor : OkColor;
        BootLog.AddMessage(FormattedMessage.FromMarkupOrThrow($"[color={color.ToHex()}]{FormattedMessage.EscapeText(text)}[/color]"));
        BootLog.ScrollToBottom();
    }

    public void SetBootProgress(float value)
    {
        var progress = Math.Clamp(value, 0f, 1f);
        BootProgress.Value = progress;
        BootProgressLabel.Text = Loc.GetString("ninja-os-boot-progress", ("percent", (int) MathF.Round(progress * 100f)));
    }

    private void ApplyFailReason()
    {
        if (string.IsNullOrEmpty(_failReason))
        {
            FailLabel.Visible = false;
            return;
        }

        var text = Loc.GetString(_failReason);
        FailLabel.Text = text;
        FailLabel.ToolTip = text;
        FailLabel.Visible = true;
    }

    private void UpdateSummary(NinjaOsBoundUserInterfaceState state)
    {
        var selected = Math.Min(state.SelectedModules.Count, _maxTier);
        ModulesLabel.Text = Loc.GetString("ninja-os-modules-count", ("selected", selected), ("total", _maxTier));

        HintLabel.Visible = selected < _maxTier;
        HintLabel.Text = Loc.GetString("ninja-os-modules-incomplete");
    }

    private void BuildModules(NinjaOsBoundUserInterfaceState state)
    {
        ModuleGrid.RemoveAllChildren();

        ModuleGrid.AddChild(MakeEmptyCell(TierCellWidth, 30f));
        foreach (var path in PathOrder)
        {
            ModuleGrid.AddChild(MakePathHeader(path));
        }

        for (var tier = 1; tier <= _maxTier; tier++)
        {
            var locked = state.LockedTiers.Contains(tier);
            var installed = state.ActivatedTiers.Contains(tier);
            var selectedPath = state.SelectedModules.TryGetValue(tier, out var path) ? path : (NinjaPath?) null;

            ModuleGrid.AddChild(MakeTierCell(tier, locked, installed));

            foreach (var candidate in PathOrder)
            {
                var selected = selectedPath == candidate;
                ModuleGrid.AddChild(MakeModuleCell(
                    tier,
                    candidate,
                    FindModule(candidate, tier),
                    selected,
                    locked,
                    selected && installed,
                    state.SuitActivated));
            }
        }
    }

    private NinjaModulePrototype? FindModule(NinjaPath path, int tier)
    {
        foreach (var module in _modules)
        {
            if (module.Path == path && module.Tier == tier)
                return module;
        }

        return null;
    }

    private Control MakeEmptyCell(float width, float height)
    {
        return new PanelContainer
        {
            MinSize = new Vector2(width, height),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = PanelColor,
                BorderColor = BorderColor,
                BorderThickness = new Thickness(1),
            },
        };
    }

    private Control MakePathHeader(NinjaPath path)
    {
        var color = PathColor(path);

        var panel = new PanelContainer
        {
            MinSize = new Vector2(CellWidth, 30f),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = new Color(color.R * 0.3f, color.G * 0.3f, color.B * 0.3f),
                BorderColor = color,
                BorderThickness = new Thickness(1),
            },
        };

        panel.AddChild(new Label
        {
            Text = Loc.GetString(PathName(path)),
            HorizontalAlignment = HAlignment.Center,
            VerticalAlignment = VAlignment.Center,
            FontColorOverride = color,
            ClipText = true,
        });

        return panel;
    }

    private Control MakeTierCell(int tier, bool locked, bool installed)
    {
        var border = installed ? OkColor : locked ? LockedColor : BorderColor;
        var panel = new PanelContainer
        {
            MinSize = new Vector2(TierCellWidth, CellHeight),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = PanelColor,
                BorderColor = border,
                BorderThickness = new Thickness(1),
            },
            ToolTip = installed
                ? Loc.GetString("ninja-os-status-installed")
                : locked
                    ? Loc.GetString("ninja-os-status-locked")
                    : null,
        };

        panel.AddChild(new Label
        {
            Text = Loc.GetString("ninja-os-tier", ("tier", tier)),
            HorizontalAlignment = HAlignment.Center,
            VerticalAlignment = VAlignment.Center,
            FontColorOverride = locked ? LockedColor : TextColor,
            ClipText = true,
        });

        return panel;
    }

    private Control MakeModuleCell(
        int tier,
        NinjaPath path,
        NinjaModulePrototype? module,
        bool selected,
        bool locked,
        bool installed,
        bool suitActivated)
    {
        if (module == null)
        {
            var empty = MakeEmptyCell(CellWidth, CellHeight);
            empty.ToolTip = Loc.GetString("ninja-os-module-missing");
            return empty;
        }

        var color = PathColor(path);
        var disabled = suitActivated || locked;

        var button = new ContainerButton
        {
            MinSize = new Vector2(CellWidth, CellHeight),
            HorizontalExpand = true,
            Disabled = disabled,
            Modulate = disabled && !selected ? new Color(1f, 1f, 1f, 0.55f) : Color.White,
            StyleBoxOverride = new StyleBoxFlat
            {
                BackgroundColor = selected
                    ? new Color(color.R * 0.45f, color.G * 0.45f, color.B * 0.45f)
                    : CellColor,
                BorderColor = selected ? color : BorderColor,
                BorderThickness = new Thickness(selected ? 2f : 1f),
                ContentMarginLeftOverride = 6f,
                ContentMarginRightOverride = 6f,
                ContentMarginTopOverride = 4f,
                ContentMarginBottomOverride = 4f,
            },
        };

        var name = Loc.GetString(module.Name);
        var description = Loc.GetString(module.Description);
        button.ToolTip = string.IsNullOrEmpty(description) ? name : $"{name}\n{description}";

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 6,
        };

        row.AddChild(new TextureRect
        {
            Texture = _sprite.Frame0(module.Icon),
            MinSize = new Vector2(32f, 32f),
            Stretch = TextureRect.StretchMode.KeepCentered,
            VerticalAlignment = VAlignment.Center,
        });

        var text = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 1,
            VerticalAlignment = VAlignment.Center,
        };

        text.AddChild(new Label
        {
            Text = name,
            FontColorOverride = TextColor,
            ClipText = true,
            ToolTip = name,
        });

        text.AddChild(new Label
        {
            Text = description,
            FontColorOverride = DimTextColor,
            ClipText = true,
            StyleClasses = { "LabelSubText" },
            ToolTip = description,
        });

        if (installed)
        {
            text.AddChild(new Label
            {
                Text = Loc.GetString("ninja-os-status-installed"),
                FontColorOverride = OkColor,
                StyleClasses = { "LabelSubText" },
                ClipText = true,
            });
        }
        else if (locked)
        {
            text.AddChild(new Label
            {
                Text = Loc.GetString("ninja-os-status-locked"),
                FontColorOverride = LockedColor,
                StyleClasses = { "LabelSubText" },
                ClipText = true,
            });
        }

        row.AddChild(text);
        button.AddChild(row);

        var capturedTier = tier;
        var capturedPath = path;
        button.OnPressed += _ => OnModuleSelected?.Invoke(capturedTier, capturedPath);

        return button;
    }

    private static LocId PathName(NinjaPath path)
    {
        return path switch
        {
            NinjaPath.Snake => "ninja-os-path-snake",
            NinjaPath.Steel => "ninja-os-path-steel",
            _ => "ninja-os-path-ghost",
        };
    }

    private static Color PathColor(NinjaPath path)
    {
        return PathColors.TryGetValue(path, out var color) ? color : TextColor;
    }
}
