namespace Content.Client._Mini.Fishing.Sources;

/// <summary>
/// Shows what the fish analyzer read: one card per fish with its icon, stats, traits and evolutions.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class FishAnalyzerWindow : FancyWindow
{
    private static readonly Color CardColor = Color.FromHex("#161a20");
    private static readonly Color CardBorder = Color.FromHex("#2c3947");
    private static readonly Color SlotColor = Color.FromHex("#0e1116");
    private static readonly Color AliveColor = Color.FromHex("#2f7d3f");
    private static readonly Color DeadColor = Color.FromHex("#7d2f2f");
    private static readonly Color GeneticColor = Color.FromHex("#5b3a86");
    private static readonly Color SubTextColor = Color.FromHex("#93a4b3");

    private const string AccentHex = "#9fb6c8";
    private const string MutedHex = "#93a4b3";

    [Dependency] private IPrototypeManager _proto = default!;
    [Dependency] private IEntityManager _ent = default!;

    private readonly SpriteSystem _sprite;

    public FishAnalyzerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sprite = _ent.System<SpriteSystem>();
    }

    public void UpdateState(FishAnalyzerBoundUserInterfaceState state)
    {
        Cards.Children.Clear();
        EmptyLabel.Visible = state.Fish.Count == 0;

        foreach (var entry in state.Fish)
            Cards.AddChild(BuildCard(entry));
    }

    private Control BuildCard(FishAnalyzerEntry entry)
    {
        var card = new PanelContainer { HorizontalExpand = true };
        card.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = CardColor,
            BorderColor = CardBorder,
            BorderThickness = new Thickness(1),
        };

        var body = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(8),
            SeparationOverride = 6,
            HorizontalExpand = true,
        };
        card.AddChild(body);

        body.AddChild(BuildHeader(entry));
        body.AddChild(BuildStats(entry));

        if (entry.Fish is { } fishId && _proto.TryIndex(fishId, out FishPrototype? fish))
        {
            if (entry.Traits.Count > 0)
                body.AddChild(BuildTraits(entry));
            if (fish.EvolutionTypes.Count > 0)
                body.AddChild(BuildEvolutions(fish));
        }

        return card;
    }

    private Control BuildHeader(FishAnalyzerEntry entry)
    {
        var header = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 10,
            HorizontalExpand = true,
        };

        var iconPanel = new PanelContainer
        {
            PanelOverride = new StyleBoxFlat(SlotColor),
            MinSize = new Vector2(64f, 64f),
            VerticalAlignment = Control.VAlignment.Center,
        };
        var icon = new TextureRect
        {
            MinSize = new Vector2(56f, 56f),
            Stretch = TextureRect.StretchMode.KeepAspectCentered,
            HorizontalAlignment = Control.HAlignment.Center,
            VerticalAlignment = Control.VAlignment.Center,
        };
        if (GetFishTexture(entry) is { } texture)
            icon.Texture = texture;
        iconPanel.AddChild(icon);
        header.AddChild(iconPanel);

        var info = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            SeparationOverride = 3,
            HorizontalExpand = true,
        };

        info.AddChild(new Label
        {
            Text = GetFishName(entry.Species),
            StyleClasses = { "LabelHeading" },
        });

        var badges = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 6,
        };
        badges.AddChild(MakeBadge(
            Loc.GetString(entry.Alive ? "fishing-analyzer-alive" : "fishing-analyzer-dead"),
            entry.Alive ? AliveColor : DeadColor));

        if (entry.HasExtraTraits)
            badges.AddChild(MakeBadge(Loc.GetString("fishing-analyzer-genetic-badge"), GeneticColor));

        info.AddChild(badges);

        var description = GetFishDescription(entry.Species);
        if (!string.IsNullOrEmpty(description))
            info.AddChild(MakeSubText(description));

        if (entry.Catcher is { } catcher)
            info.AddChild(MakeSubText(Loc.GetString("fishing-analyzer-catcher", ("catcher", catcher))));

        if (entry.CatchMinutes >= 0f)
            info.AddChild(MakeSubText(Loc.GetString("fishing-analyzer-date", ("minutes", (int) entry.CatchMinutes))));

        header.AddChild(info);
        return header;
    }

    private Control BuildStats(FishAnalyzerEntry entry)
    {
        var grid = new GridContainer { Columns = 2, HorizontalExpand = true };

        grid.AddChild(MakeStatChip(
            Loc.GetString("fishing-analyzer-stat-size"),
            Loc.GetString("fishing-analyzer-size-value", ("size", (int) MathF.Round(entry.Size)))));
        grid.AddChild(MakeStatChip(
            Loc.GetString("fishing-analyzer-stat-weight"),
            Loc.GetString("fishing-analyzer-weight-value", ("weight", (entry.Weight / 1000f).ToString("0.00")))));

        if (entry.Fish is not { } fishId || !_proto.TryIndex(fishId, out FishPrototype? fish))
            return grid;

        grid.AddChild(MakeStatChip(
            Loc.GetString("fishing-analyzer-stat-fluid"),
            FishUiHelpers.GetFluidName(fish.Fluid)));
        grid.AddChild(MakeStatChip(
            Loc.GetString("fishing-analyzer-stat-temperature"),
            Loc.GetString("fishing-analyzer-temperature-value",
                ("min", FishUiHelpers.KelvinToCelsius(fish.TemperatureMin)),
                ("max", FishUiHelpers.KelvinToCelsius(fish.TemperatureMax)))));

        if (fish.Beauty != 0)
        {
            grid.AddChild(MakeStatChip(
                Loc.GetString("fishing-analyzer-stat-beauty"),
                fish.Beauty.ToString()));
        }

        return grid;
    }

    private static Control MakeStatChip(string title, string value)
    {
        var panel = new PanelContainer
        {
            PanelOverride = new StyleBoxFlat(SlotColor),
            HorizontalExpand = true,
            Margin = new Thickness(2),
        };

        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(6, 4),
            SeparationOverride = 1,
        };

        box.AddChild(new Label
        {
            Text = title,
            StyleClasses = { "LabelSubText" },
            FontColorOverride = SubTextColor,
        });
        box.AddChild(new Label { Text = value });

        panel.AddChild(box);
        return panel;
    }

    private Control BuildTraits(FishAnalyzerEntry entry)
    {
        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            SeparationOverride = 2,
        };

        box.AddChild(MakeSectionHeader("fishing-analyzer-traits-title"));

        var msg = new FormattedMessage();
        foreach (var traitId in entry.Traits)
        {
            if (!_proto.TryIndex<FishTraitPrototype>(traitId, out var trait))
                continue;

            var name = FormattedMessage.EscapeText(Loc.GetString(trait.Name));
            var desc = FormattedMessage.EscapeText(Loc.GetString(trait.CatalogDescription));
            msg.AddMarkupOrThrow($"[color={AccentHex}]\u2022[/color] [bold]{name}[/bold] [color={MutedHex}]{desc}[/color]");
            msg.PushNewline();
        }

        if (entry.HasExtraTraits)
        {
            msg.AddMarkupOrThrow($"[color={MutedHex}]{FormattedMessage.EscapeText(Loc.GetString("fishing-analyzer-traits-genetic"))}[/color]");
            msg.PushNewline();
        }

        box.AddChild(MakeRichText(msg));
        return box;
    }

    private Control BuildEvolutions(FishPrototype fish)
    {
        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            SeparationOverride = 2,
        };

        box.AddChild(MakeSectionHeader("fishing-analyzer-evolutions-title"));

        var msg = new FormattedMessage();
        foreach (var evolutionId in fish.EvolutionTypes)
        {
            if (!_proto.TryIndex(evolutionId, out FishEvolutionPrototype? evolution))
                continue;

            var evolvedInto = FormattedMessage.EscapeText(GetFishName(evolution.EvolvesTo.Id));
            var chance = MathF.Round(evolution.Probability * 100f);
            var note = evolution.ConditionsNote is { } noteId
                ? " " + FormattedMessage.EscapeText(Loc.GetString(noteId))
                : string.Empty;
            msg.AddMarkupOrThrow($"[color={AccentHex}]\u2192[/color] [bold]{evolvedInto}[/bold] [color={MutedHex}]{chance}%{note}[/color]");
            msg.PushNewline();
        }

        box.AddChild(MakeRichText(msg));
        return box;
    }

    private static Label MakeSectionHeader(string locKey)
    {
        return new Label
        {
            Text = Loc.GetString(locKey),
            StyleClasses = { "LabelSubText" },
            FontColorOverride = SubTextColor,
            Margin = new Thickness(0, 4, 0, 0),
        };
    }

    private static Label MakeSubText(string text)
    {
        return new Label
        {
            Text = text,
            StyleClasses = { "LabelSubText" },
            FontColorOverride = SubTextColor,
        };
    }

    private static RichTextLabel MakeRichText(FormattedMessage msg)
    {
        var label = new RichTextLabel();
        label.SetMessage(msg);
        return label;
    }

    private static Control MakeBadge(string text, Color color)
    {
        var badge = new PanelContainer
        {
            PanelOverride = new StyleBoxFlat(color),
            VerticalAlignment = Control.VAlignment.Center,
        };
        badge.AddChild(new Label
        {
            Text = text,
            Margin = new Thickness(6, 1),
            FontColorOverride = Color.White,
        });
        return badge;
    }

    private Texture? GetFishTexture(FishAnalyzerEntry entry)
    {
        if (entry.Fish is { } fishId && _proto.TryIndex(fishId, out FishPrototype? fish))
            return _sprite.Frame0(fish.Sprite);

        return null;
    }

    private string GetFishName(string species)
    {
        if (_proto.TryIndex<EntityPrototype>(species, out var proto))
        {
            if (Loc.TryGetString($"ent-{species}", out var localized))
                return localized;

            return proto.Name;
        }

        return species;
    }

    private string GetFishDescription(string species)
    {
        if (Loc.TryGetString($"ent-{species}.desc", out var localized))
            return localized;

        return _proto.TryIndex<EntityPrototype>(species, out var proto) ? proto.Description : string.Empty;
    }
}
