using Content.Shared._Mini.Fishing.Prototypes;
using Content.Shared._Mini.Fishing.Sources;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._Mini.Fishing.Sources;

[GenerateTypedNameReferences]
public sealed partial class FishAnalyzerWindow : DefaultWindow
{
    [Dependency] private IPrototypeManager _proto = default!;

    public FishAnalyzerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void UpdateState(FishAnalyzerBoundUserInterfaceState state)
    {
        var msg = new FormattedMessage();

        for (var i = 0; i < state.Fish.Count; i++)
        {
            if (i > 0)
                msg.PushNewline();

            AppendFish(msg, state.Fish[i]);
        }

        FishInfo.SetMessage(msg);
    }

    private void AppendFish(FormattedMessage msg, FishAnalyzerEntry entry)
    {
        msg.AddMarkupOrThrow($"[bold]{FormattedMessage.EscapeText(GetFishName(entry.Species))}[/bold]");
        msg.PushNewline();

        var description = GetFishDescription(entry.Species);
        if (!string.IsNullOrEmpty(description))
        {
            msg.AddText(description);
            msg.PushNewline();
        }

        msg.PushNewline();
        AddLine(msg, Loc.GetString("fishing-analyzer-status",
            ("status", Loc.GetString(entry.Alive ? "fishing-analyzer-alive" : "fishing-analyzer-dead"))));
        AddLine(msg, Loc.GetString("fishing-analyzer-size-weight",
            ("size", MathF.Round(entry.Size)),
            ("weight", MathF.Round(entry.Weight))));

        if (entry.Catcher is { } catcher)
            AddLine(msg, Loc.GetString("fishing-analyzer-catcher", ("catcher", catcher)));

        if (entry.CatchMinutes >= 0f)
            AddLine(msg, Loc.GetString("fishing-analyzer-date", ("minutes", (int) entry.CatchMinutes)));

        if (entry.Fish is not { } fishId || !_proto.TryIndex(fishId, out FishPrototype? fish))
            return;

        msg.PushNewline();
        AddLine(msg, Loc.GetString("fishing-analyzer-fluid", ("fluid", FishUiHelpers.GetFluidName(fish.Fluid))));
        AddLine(msg, Loc.GetString("fishing-analyzer-temperature",
            ("min", FishUiHelpers.KelvinToCelsius(fish.TemperatureMin)),
            ("max", FishUiHelpers.KelvinToCelsius(fish.TemperatureMax))));

        if (fish.Beauty != 0)
            AddLine(msg, Loc.GetString("fishing-analyzer-beauty", ("beauty", fish.Beauty)));

        if (entry.Traits.Count > 0)
        {
            msg.PushNewline();
            AddLine(msg, Loc.GetString("fishing-analyzer-traits-title"));

            foreach (var traitId in entry.Traits)
            {
                if (!_proto.TryIndex<FishTraitPrototype>(traitId, out var trait))
                    continue;

                msg.AddMarkupOrThrow("  - ");
                msg.AddText(Loc.GetString(trait.CatalogDescription));
                msg.PushNewline();
            }

            if (entry.HasExtraTraits)
                AddLine(msg, Loc.GetString("fishing-analyzer-traits-genetic"));
        }

        if (fish.EvolutionTypes.Count > 0)
        {
            msg.PushNewline();
            AddLine(msg, Loc.GetString("fishing-analyzer-evolutions-title"));

            foreach (var evolutionId in fish.EvolutionTypes)
            {
                if (!_proto.TryIndex(evolutionId, out FishEvolutionPrototype? evolution))
                    continue;

                var evolvesTo = GetFishName(evolution.EvolvesTo.Id);
                AddLine(msg, Loc.GetString("fishing-analyzer-evolution",
                    ("fish", evolvesTo),
                    ("probability", MathF.Round(evolution.Probability * 100f))));

                if (evolution.ConditionsNote is { } note)
                {
                    msg.AddText("  ");
                    msg.AddText(Loc.GetString(note));
                    msg.PushNewline();
                }
            }
        }
    }

    private static void AddLine(FormattedMessage msg, string line)
    {
        msg.AddText(line);
        msg.PushNewline();
    }

    private string GetFishName(string species)
    {
        if (_proto.TryIndex<EntityPrototype>(species, out var proto))
        {
            if (Loc.TryGetString($"ent-{species}", out var localized))
                return localized;

            return proto.Name;
        }

        return species;
    }

    private string GetFishDescription(string species)
    {
        if (Loc.TryGetString($"ent-{species}.desc", out var localized))
            return localized;

        return _proto.TryIndex<EntityPrototype>(species, out var proto) ? proto.Description : string.Empty;
    }
}
