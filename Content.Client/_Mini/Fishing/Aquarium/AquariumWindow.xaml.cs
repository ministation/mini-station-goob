using System.Linq;
using System.Numerics;
using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Robust.Client.UserInterface;
using Content.Shared._Mini.Fishing;
using Content.Shared._Mini.Fishing.Aquarium;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Mini.Fishing.Aquarium;

/// <summary>
/// Aquarium control window: tank settings on top, the fish list and the decoration list below.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class AquariumWindow : FancyWindow
{
    [Dependency] private IEntityManager _ent = default!;
    [Dependency] private IPrototypeManager _proto = default!;

    private readonly SpriteSystem _sprite;
    private readonly Dictionary<NetEntity, FishRow> _fishRows = new();

    public event Action<float>? OnTemperatureSelected;
    public event Action<AquariumFluid>? OnFluidSelected;
    public event Action<AquariumMode>? OnModeSelected;
    public event Action? OnFeed;
    public event Action<NetEntity>? OnRemove;

    private static readonly AquariumMode[] Modes =
    {
        AquariumMode.Manual,
        AquariumMode.Assisted,
        AquariumMode.Stasis,
    };

    private bool _updating;

    public AquariumWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sprite = _ent.System<SpriteSystem>();

        for (var i = 0; i < SharedAquariumSystem.Fluids.Length; i++)
        {
            FluidSelector.AddItem(Loc.GetString(FluidLoc(SharedAquariumSystem.Fluids[i])), i);
        }

        FluidSelector.OnItemSelected += args =>
        {
            if (!_updating)
                OnFluidSelected?.Invoke(SharedAquariumSystem.Fluids[args.Id]);
        };

        for (var i = 0; i < Modes.Length; i++)
        {
            ModeSelector.AddItem(Loc.GetString(ModeLoc(Modes[i])), i);
        }

        ModeSelector.OnItemSelected += args =>
        {
            if (!_updating)
                OnModeSelected?.Invoke(Modes[args.Id]);
        };

        TemperatureSpin.ValueChanged += args =>
        {
            if (!_updating)
                OnTemperatureSelected?.Invoke(args.Value);
        };

        FeedButton.OnPressed += _ => OnFeed?.Invoke();
    }

    public void UpdateState(AquariumBoundUserInterfaceState state)
    {
        _updating = true;

        var manual = state.Mode == AquariumMode.Manual;

        FluidSelector.SelectId(Array.IndexOf(SharedAquariumSystem.Fluids, state.Fluid));
        FluidSelector.Disabled = !manual;

        TemperatureSpin.IsValid = value =>
            manual && value >= state.MinTemperature && value <= state.MaxTemperature;
        TemperatureSpin.OverrideValue((int) MathF.Round(state.Temperature));
        TemperatureSpin.LineEditControl.Editable = manual;
        TemperatureLabel.Text = Loc.GetString("aquarium-window-kelvin",
            ("temperature", (int) MathF.Round(state.Temperature)));

        ModeSelector.SelectId(Array.IndexOf(Modes, state.Mode));

        BeautyLabel.Text = Loc.GetString("aquarium-window-beauty", ("beauty", state.Beauty));
        CountLabel.Text = Loc.GetString("aquarium-window-count", ("count", state.Fish.Length), ("max", state.MaxFish));

        BrokenLabel.Visible = state.GlassBroken;
        FeedButton.Disabled = state.GlassBroken;

        Tank.SetFish(state.Fish, state.GlassBroken, state.Fluid);

        UpdateFish(state);
        UpdateProps(state);

        _updating = false;
    }

    private void UpdateFish(AquariumBoundUserInterfaceState state)
    {
        var seen = new HashSet<NetEntity>();

        foreach (var fish in state.Fish)
        {
            seen.Add(fish.Entity);

            if (!_fishRows.TryGetValue(fish.Entity, out var row))
            {
                row = new FishRow(fish.Entity, OnRemovePressed);
                FishList.AddChild(row.Root);
                _fishRows[fish.Entity] = row;
            }

            row.Update(fish, GetIcon(fish.Prototype));
        }

        foreach (var (net, row) in _fishRows.ToArray())
        {
            if (seen.Contains(net))
                continue;

            FishList.Children.Remove(row.Root);
            _fishRows.Remove(net);
        }
    }

    private void UpdateProps(AquariumBoundUserInterfaceState state)
    {
        PropList.Children.Clear();

        foreach (var prop in state.Props)
        {
            var row = new PropRow(prop, OnRemovePressed, GetIcon(prop.Prototype));
            PropList.AddChild(row.Root);
        }
    }

    private Texture? GetIcon(string prototype)
    {
        if (string.IsNullOrEmpty(prototype) || !_proto.TryIndex<EntityPrototype>(prototype, out var entProto))
            return null;

        return _sprite.GetPrototypeIcon(entProto).Default;
    }

    private void OnRemovePressed(NetEntity entity)
    {
        OnRemove?.Invoke(entity);
    }

    private static string FluidLoc(AquariumFluid fluid)
    {
        return $"aquarium-fluid-{fluid.ToString().ToLowerInvariant()}";
    }

    private static string ModeLoc(AquariumMode mode)
    {
        return $"aquarium-mode-{mode.ToString().ToLowerInvariant()}";
    }

    private sealed class FishRow
    {
        public readonly BoxContainer Root;
        private readonly TextureRect _icon;
        private readonly Label _name;
        private readonly RichTextLabel _info;

        public FishRow(NetEntity entity, Action<NetEntity> onRemove)
        {
            Root = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                Margin = new Thickness(4f, 2f),
            };

            _icon = new TextureRect
            {
                MinSize = new Vector2(40f, 40f),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
            };
            Root.AddChild(_icon);

            var texts = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
                Margin = new Thickness(6f, 0f),
            };

            _name = new Label { HorizontalExpand = true };
            _info = new RichTextLabel { HorizontalExpand = true };

            texts.AddChild(_name);
            texts.AddChild(_info);
            Root.AddChild(texts);

            var remove = new Button
            {
                Text = Loc.GetString("aquarium-window-remove"),
                MinSize = new Vector2(90f, 0f),
                VerticalAlignment = Control.VAlignment.Center,
            };
            remove.OnPressed += _ => onRemove(entity);
            Root.AddChild(remove);
        }

        public void Update(AquariumFishData data, Texture? icon)
        {
            _name.Text = data.Name;
            _icon.Texture = icon;

            if (data.Alive)
            {
                var info = Loc.GetString("aquarium-window-fish-info",
                    ("hunger", (int) (data.Hunger * 100)),
                    ("happiness", data.Happiness),
                    ("size", (int) data.Size),
                    ("weight", (int) data.Weight));

                if (data.Hunger >= 1f)
                    info += "\n" + Loc.GetString("aquarium-window-fish-starving");

                _info.SetMarkup(info);
            }
            else
            {
                _info.SetMarkup(Loc.GetString("aquarium-window-fish-dead"));
            }
        }
    }

    private sealed class PropRow
    {
        public readonly BoxContainer Root;
        private readonly TextureRect _icon;
        private readonly Label _name;

        public PropRow(AquariumPropData data, Action<NetEntity> onRemove, Texture? icon)
        {
            Root = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                Margin = new Thickness(4f, 2f),
            };

            _icon = new TextureRect
            {
                MinSize = new Vector2(32f, 32f),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                Texture = icon,
            };
            Root.AddChild(_icon);

            _name = new Label
            {
                HorizontalExpand = true,
                VerticalAlignment = Control.VAlignment.Center,
                Text = Loc.GetString("aquarium-window-prop-info", ("name", data.Name), ("beauty", data.Beauty)),
            };
            Root.AddChild(_name);

            var remove = new Button
            {
                Text = Loc.GetString("aquarium-window-remove"),
                MinSize = new Vector2(90f, 0f),
                VerticalAlignment = Control.VAlignment.Center,
            };
            remove.OnPressed += _ => onRemove(data.Entity);
            Root.AddChild(remove);
        }
    }
}
