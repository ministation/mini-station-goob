namespace Content.Client._Mini.Latejoin;

[GenerateTypedNameReferences]
public sealed partial class NFLateJoinGui : FancyWindow
{
    [Dependency] private readonly IPrototypeManager _prototypeManager = default!;
    [Dependency] private readonly IConsoleHost _consoleHost = default!;
    [Dependency] private readonly JobRequirementsManager _playManager = default!;
    [Dependency] private readonly IClientPreferencesManager _preferencesManager = default!;

    private ClientGameTicker _gameTicker;
    private TypanWarUiSystem _warUi;
    private KatorgaUiSystem _katorgaUi;
    [Dependency] private readonly KatorgaBanManager _katorgaBans = default!;

    private NetEntity _lastSelection;

    private readonly Dictionary<string, BoxContainer> _jobCategories;
    private readonly Dictionary<string, NewFrontierLateJoinJobButton> _buttons = new();
    private readonly List<Button> _factionButtons = new();

    // Временно забаненный видит только должность заключённого и никаких станций.
    private bool _prisonerMode;
    private int _lastBanSecond = -1;
    private int _lastFactionSecond = -1;

    public NFLateJoinGui()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _gameTicker = EntitySystem.Get<ClientGameTicker>();
        _warUi = EntitySystem.Get<TypanWarUiSystem>();
        _katorgaUi = EntitySystem.Get<KatorgaUiSystem>();
        _gameTicker.LobbyJobsAvailableUpdated += UpdateUi;
        _warUi.BalanceUpdated += OnBalanceUpdated;
        _katorgaBans.BanStatusChanged += OnBanStatusChanged;
        _katorgaUi.FactionStateChanged += OnFactionStateChanged;

        _jobCategories = new Dictionary<string, BoxContainer>();
        StationSelection.StationsItemList.OnItemSelected += args =>
        {
            UpdateUi(_gameTicker.JobsAvailable);
        };
        CrewManifestButton.OnPressed += _ =>
        {
            EntitySystem.Get<CrewManifestSystem>().RequestCrewManifest(_lastSelection);
        };

        _lastSelection = _gameTicker.JobsAvailable.Keys.FirstOrNull() ?? NetEntity.Invalid;

        _warUi.RequestBalanceStatus();
        _katorgaUi.RequestFactionState();
        UpdateUi(_gameTicker.JobsAvailable);
        UpdateBalanceNotice();
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);
        _gameTicker.LobbyJobsAvailableUpdated -= UpdateUi;
        _warUi.BalanceUpdated -= OnBalanceUpdated;
        _katorgaBans.BanStatusChanged -= OnBanStatusChanged;
        _katorgaUi.FactionStateChanged -= OnFactionStateChanged;
    }

    private void OnBanStatusChanged()
    {
        UpdateUi(_gameTicker.JobsAvailable);
    }

    private void OnFactionStateChanged()
    {
        if (_prisonerMode)
            RebuildFactionUi();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        // Срок тикает сам по себе, а после его конца окно возвращается к обычному виду
        // без ожидания следующего события от сервера.
        if (_prisonerMode || _katorgaBans.TryGetActiveBan(out _))
            UpdateUi(_gameTicker.JobsAvailable);
    }

    private void OnBalanceUpdated()
    {
        UpdateBalanceNotice();
        ApplyBalanceToButtons();
    }

    public void UpdateUi(IReadOnlyDictionary<NetEntity, Dictionary<ProtoId<JobPrototype>, int?>> obj)
    {
        // Временно забаненный не выбирает станцию и роль: его единственная должность - заключённый.
        if (_katorgaBans.TryGetActiveBan(out var banRemaining))
        {
            UpdatePrisonerUi(banRemaining, obj);
            return;
        }

        if (_prisonerMode)
        {
            _prisonerMode = false;
            _lastBanSecond = -1;
            BanNotice.Visible = false;
            HideFactionUi();
            ClearJobList();
            _lastSelection = NetEntity.Invalid;
        }

        StationsScroll.Visible = true;
        NavSeparator.Visible = true;

        if (StationSelection.Selected is null)
        {
            CrewManifestButton.Visible = false;
            return;
        }

        CrewManifestButton.Visible = true;

        var station = StationSelection.Selected.Value;
        if (!obj.TryGetValue(station, out var jobs))
            return;

        if (station != _lastSelection)
            ClearJobList();

        _lastSelection = station;

        var departments = new List<DepartmentPrototype>();
        foreach (var department in _prototypeManager.EnumeratePrototypes<DepartmentPrototype>())
        {
            if (department.EditorHidden)
                continue;

            departments.Add(department);
        }

        departments.Sort(DepartmentUIComparer.Instance);

        foreach (var department in departments)
        {
            var departmentName = Loc.GetString($"department-{department.ID}");

            var hasRole = false;
            foreach (var (jobId, _) in jobs)
            {
                if (department.Roles.Contains(jobId))
                {
                    hasRole = true;
                    break;
                }
            }

            if (!hasRole)
            {
                continue;
            }

            if (!_jobCategories.TryGetValue(department.ID, out var category))
            {
                category = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Vertical,
                    Name = department.ID,
                    ToolTip = Loc.GetString("humanoid-profile-editor-jobs-amount-in-department-tooltip",
                        ("departmentName", departmentName))
                };

                var departamentLabel = new Label
                {
                    Text = Loc.GetString("humanoid-profile-editor-department-jobs-label",
                        ("departmentName", departmentName)),
                    Margin = new Thickness(5f, 0, 0, 0)
                };

                category.AddChild(new StripeBack()
                {
                    Visible = true,
                    HorizontalExpand = true,
                    HasMargins = true,
                    MouseFilter = MouseFilterMode.Stop,
                    Children =
                    {
                        departamentLabel
                    }
                });

                _jobCategories[department.ID] = category;
                JobList.AddChild(category);
            }

            foreach (var (jobId, _) in jobs)
            {
                if (!department.Roles.Contains(jobId) || jobId == KatorgaJobs.Prisoner)
                    continue;

                if (_buttons.ContainsKey(jobId))
                    continue;

                var job = _prototypeManager.Index(jobId);

                var newButton = new NewFrontierLateJoinJobButton(station, jobId, _gameTicker, _prototypeManager);
                newButton.OnPressed += _ =>
                {
                    Logger.InfoS("latejoin", $"Late joining as ID: {jobId}");
                    _consoleHost.ExecuteCommand($"joingame {CommandParsing.Escape(jobId)} {station}");
                    Close();
                };

                RefreshButtonState(newButton, jobId);

                JobList.AddChild(newButton);

                _buttons.Add(jobId, newButton);
            }
        }

        ApplyBalanceToButtons();
        UpdateBalanceNotice();
    }

    /// <summary>
    ///     Режим временно забаненного: станции и прочие роли скрыты, доступна одна должность -
    ///     заключённый. Сервер всё равно отправит такого игрока на каторгу, а не на станцию.
    /// </summary>
    private void UpdatePrisonerUi(TimeSpan remaining, IReadOnlyDictionary<NetEntity, Dictionary<ProtoId<JobPrototype>, int?>> obj)
    {
        StationsScroll.Visible = false;
        NavSeparator.Visible = false;
        CrewManifestButton.Visible = false;
        BalanceNotice.Visible = false;

        var second = (int) remaining.TotalSeconds;
        if (second != _lastBanSecond)
        {
            _lastBanSecond = second;
            BanNotice.Text = Loc.GetString("katorga-ban-latejoin", ("time", KatorgaTime.Format(remaining)));
        }

        BanNotice.Visible = true;

        // Кнопку собираем один раз: у станции, где должность реально есть и не лимитирована.
        if (!_prisonerMode)
        {
            _prisonerMode = true;
            ClearJobList();
            RebuildFactionUi();
        }
        else
        {
            UpdateFactionCountdown();
            if (_buttons.Count > 0)
                return;
        }

        var station = obj
            .Where(kv => kv.Value.ContainsKey(KatorgaJobs.Prisoner))
            .Select(kv => kv.Key)
            .FirstOrDefault();

        if (station == NetEntity.Invalid)
            return;

        _lastSelection = station;

        var button = new NewFrontierLateJoinJobButton(station, KatorgaJobs.Prisoner, _gameTicker, _prototypeManager);
        button.OnPressed += args =>
        {
            // Пока кнопка висела, срок мог закончиться: тогда просто перерисовываем окно.
            if (!_katorgaBans.TryGetActiveBan(out _))
            {
                UpdateUi(_gameTicker.JobsAvailable);
                return;
            }

            Logger.InfoS("latejoin", "Late joining as prisoner (katorga)");
            _consoleHost.ExecuteCommand($"joingame {KatorgaJobs.Prisoner} {station}");
            Close();
        };

        JobList.AddChild(button);
        _buttons[KatorgaJobs.Prisoner] = button;
    }

    /// <summary>
    ///     Выбор фракции каторги в окне позднего подключения: кнопки с названием и описанием
    ///     и отсчёт до автоназначения. Фракция уже выбрана - показываем её без кнопок.
    /// </summary>
    private void RebuildFactionUi()
    {
        FactionList.RemoveAllChildren();
        _factionButtons.Clear();
        _lastFactionSecond = -1;

        var state = _katorgaUi.FactionState;
        if (state == null || state.Options.Count == 0)
        {
            HideFactionUi();
            return;
        }

        FactionNotice.Visible = true;
        FactionList.Visible = true;

        if (state.Selected != null)
        {
            var selected = state.Options.FirstOrDefault(option => option.Id == state.Selected);
            FactionNotice.Text = Loc.GetString("katorga-faction-selected", ("faction", selected?.Name ?? state.Selected));
            FactionList.Visible = false;
            return;
        }

        foreach (var option in state.Options)
        {
            var choice = option;
            var button = new Button
            {
                Text = choice.Name,
                MinHeight = 34,
            };
            button.OnPressed += _ => _katorgaUi.RequestFactionSelect(choice.Id);
            FactionList.AddChild(button);
            _factionButtons.Add(button);

            var feature = new RichTextLabel();
            feature.SetMessage(FormattedMessage.FromMarkupPermissive(choice.Feature));
            FactionList.AddChild(feature);
        }

        UpdateFactionCountdown();
    }

    /// <summary>Обновляет строку отсчёта и гасит кнопки, когда время на выбор вышло.</summary>
    private void UpdateFactionCountdown()
    {
        var state = _katorgaUi.FactionState;
        if (state == null || state.Selected != null || _factionButtons.Count == 0)
            return;

        var second = _katorgaUi.FactionSecondsRemaining;
        if (second == _lastFactionSecond)
            return;

        _lastFactionSecond = second;
        FactionNotice.Text = second > 0
            ? Loc.GetString("katorga-faction-latejoin-countdown", ("seconds", second))
            : Loc.GetString("katorga-faction-latejoin-assigning");

        foreach (var button in _factionButtons)
            button.Disabled = second <= 0;
    }

    private void HideFactionUi()
    {
        FactionNotice.Visible = false;
        FactionList.Visible = false;
        FactionList.RemoveAllChildren();
        _factionButtons.Clear();
        _lastFactionSecond = -1;
    }

    private void ClearJobList()
    {
        foreach (var (_, button) in _buttons)
        {
            JobList.RemoveChild(button);
        }

        _buttons.Clear();

        foreach (var (_, box) in _jobCategories)
        {
            JobList.RemoveChild(box);
        }

        _jobCategories.Clear();
    }

    private void UpdateBalanceNotice()
    {
        if (_prisonerMode || !_warUi.BalanceActive)
        {
            BalanceNotice.Visible = false;
            return;
        }

        string? text = null;
        if (!_warUi.AllowNanotrasen && _warUi.AllowTypan)
            text = Loc.GetString("typan-war-balance-latejoin-nt-full");
        else if (!_warUi.AllowTypan && _warUi.AllowNanotrasen)
            text = Loc.GetString("typan-war-balance-latejoin-typan-full");
        else if (!_warUi.AllowNanotrasen && !_warUi.AllowTypan)
            text = Loc.GetString("typan-war-balance-latejoin-both-full");

        if (text == null)
        {
            BalanceNotice.Visible = false;
            return;
        }

        BalanceNotice.Text = text;
        BalanceNotice.Visible = true;
    }

    private void ApplyBalanceToButtons()
    {
        if (_prisonerMode)
            return;

        foreach (var (jobId, button) in _buttons)
        {
            RefreshButtonState(button, jobId);
        }
    }

    private void RefreshButtonState(NewFrontierLateJoinJobButton button, ProtoId<JobPrototype> jobId)
    {
        var job = _prototypeManager.Index(jobId);

        if (!_playManager.IsAllowed(job, (HumanoidCharacterProfile?)_preferencesManager.Preferences?.SelectedCharacter, out var denyReason))
        {
            button.Disabled = true;
            button.ToolTip = denyReason.ToString();
            return;
        }

        if (_warUi.BalanceActive)
        {
            var isTypan = IsTypanJob(jobId);
            var blocked = isTypan ? !_warUi.AllowTypan : !_warUi.AllowNanotrasen;
            if (blocked)
            {
                button.Disabled = true;
                button.ToolTip = Loc.GetString("typan-war-balance-job-denied");
                return;
            }
        }

        if (IsJobSlotFull(jobId))
        {
            button.Disabled = true;
            button.ToolTip = Loc.GetString("late-join-gui-job-slot-full");
            return;
        }

        button.Disabled = false;
        button.ToolTip = null;
    }

    private bool IsJobSlotFull(ProtoId<JobPrototype> jobId)
    {
        if (!_gameTicker.JobsAvailable.TryGetValue(_lastSelection, out var jobs))
            return true;

        if (!jobs.TryGetValue(jobId, out var count))
            return true;

        return count == 0;
    }

    private bool IsTypanJob(ProtoId<JobPrototype> jobId)
    {
        foreach (var department in _prototypeManager.EnumeratePrototypes<DepartmentPrototype>())
        {
            if (department.ID is not ("Typan" or "Typan2"))
                continue;

            if (department.Roles.Contains(jobId))
                return true;
        }

        return false;
    }
}
