using System.Linq;
using Content.Client.Message;
using Content.Shared._Mini.DecaCode;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using FancyWindow = Content.Client.UserInterface.Controls.FancyWindow;

namespace Content.Client._Mini.DecaCode.UI;

[GenerateTypedNameReferences]
public sealed partial class DecaCodeLockWindow : FancyWindow
{
    private const string ExactColor = "#6ABF69";
    private const string PartialColor = "#FFD700";

    public event Action<string>? OnSubmit;

    public DecaCodeLockWindow()
    {
        RobustXamlLoader.Load(this);

        BombWarningPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#7A1010"),
            BorderColor = Color.FromHex("#C43A3A"),
            BorderThickness = new Thickness(1),
        };

        CodeLineEdit.OnTextChanged += OnCodeChanged;
        CodeLineEdit.OnTextEntered += _ => TrySubmit();
        SubmitButton.OnPressed += _ => TrySubmit();
        SubmitButton.Disabled = true;
    }

    /// <summary>
    /// Rebuilds the whole window from the server state. Called after every submit and after every
    /// multitool refresh, so the grid is cleared first to guarantee there are no duplicate rows.
    /// </summary>
    public void UpdateState(DecaCodeLockState state)
    {
        BombWarningLabel.SetMessage(
            Loc.GetString("deca-code-lock-bomb-warning", ("attempts", state.RemainingAttempts)),
            Color.White);

        AttemptsGrid.RemoveAllChildren();

        AttemptsGrid.AddChild(new Label { Text = Loc.GetString("deca-code-lock-attempt") });
        AttemptsGrid.AddChild(CreateMarkupLabel(
            $"[color={ExactColor}]✔[/color] {Loc.GetString("deca-code-lock-check")}"));
        AttemptsGrid.AddChild(CreateMarkupLabel(
            $"[color={PartialColor}]★[/color] {Loc.GetString("deca-code-lock-star")}"));

        foreach (var attempt in state.Attempts)
        {
            AttemptsGrid.AddChild(new Label { Text = attempt.Input });
            AttemptsGrid.AddChild(CreateMarkupLabel($"[color={ExactColor}]✔[/color] {attempt.ExactMatches}"));
            AttemptsGrid.AddChild(CreateMarkupLabel($"[color={PartialColor}]★[/color] {attempt.PartialMatches}"));
        }
    }

    private static RichTextLabel CreateMarkupLabel(string markup)
    {
        var label = new RichTextLabel();
        label.SetMarkup(markup);
        return label;
    }

    private void OnCodeChanged(LineEdit.LineEditEventArgs args)
    {
        var filtered = new string(args.Text.Where(c => c is >= '0' and <= '9').ToArray());
        if (filtered.Length > DecaCodeLockComponent.CodeLength)
            filtered = filtered[..DecaCodeLockComponent.CodeLength];

        if (filtered != args.Text)
        {
            // The text setter fires OnTextChanged again; that pass updates the button state.
            CodeLineEdit.Text = filtered;
            return;
        }

        SubmitButton.Disabled = !IsCompleteCode(filtered);
    }

    private void TrySubmit()
    {
        var code = CodeLineEdit.Text;
        if (!IsCompleteCode(code))
            return;

        OnSubmit?.Invoke(code);
        CodeLineEdit.Text = string.Empty;
        SubmitButton.Disabled = true;
    }

    private static bool IsCompleteCode(string code)
    {
        if (code.Length != DecaCodeLockComponent.CodeLength)
            return false;

        var seen = new bool[10];
        foreach (var c in code)
        {
            if (c is < '0' or > '9')
                return false;

            var digit = c - '0';
            if (seen[digit])
                return false;

            seen[digit] = true;
        }

        return true;
    }
}
